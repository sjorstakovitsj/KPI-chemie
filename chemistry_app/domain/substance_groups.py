def classify_substance_group(substance: str) -> str:
    """Classify one substance using the current ordered substring rules.

    This intentionally preserves the legacy first-match behavior. A later phase
    can replace it with explicit parameter-code and alias mappings.
    """
    normalized = str(substance).strip().casefold()
    for group, keywords in STOFGROEPEN_MAPPING.items():
        if any(keyword.casefold() in normalized for keyword in keywords):
            return group
    return "Onbekend"


def match_stofgroep_optimized(unique_substances: Iterable[str]) -> dict[str, str]:
    """Backward-compatible bulk classifier used by the current utils module."""
    return {substance: classify_substance_group(substance) for substance in unique_substances}


